import { Entity, PrimaryGeneratedColumn, Column, ManyToOne, JoinColumn, Index } from 'typeorm';
import { ApiProperty } from '@nestjs/swagger';
import { LlmModelTestRun } from './llm-model-test-run.entity';

/**
 * Per-model metrics captured by a single LlmModelTestRun.
 *
 * Holds latency, throughput, token usage, and a heuristic quality score.
 * These rows are read by the ranking service to compute overall model
 * scores and by the Settings UI to display per-model history.
 */
@Entity('llm_model_test_results')
@Index(['providerKey', 'modelName', 'testedAt'])
@Index(['runId'])
@Index(['modelId'])
export class LlmModelTestResult {
  @ApiProperty({ description: 'Unique numeric result id.', example: 134 })
  @PrimaryGeneratedColumn()
  id!: number;

  @ApiProperty({ description: 'Owning test run id (FK to llm_model_test_runs.id).', example: 12 })
  @Column()
  runId!: number;

  @ApiProperty({
    description: 'Owning test run. Backref only — runId is the persisted FK column.',
    type: () => LlmModelTestRun,
  })
  @ManyToOne(() => LlmModelTestRun, (r) => r.results)
  @JoinColumn({ name: 'runId' })
  run!: LlmModelTestRun;

  @ApiProperty({ description: 'Provider id at the time of the test. Kept denormalized to survive provider changes.', example: 1 })
  @Column()
  providerId!: number;

  @ApiProperty({
    description: 'Model id at the time of the test, or null if the model is not in the DB (e.g. runtime Ollama).',
    example: 7,
    nullable: true,
  })
  @Column({ nullable: true })
  modelId!: number | null;

  @ApiProperty({ description: 'Provider routing key at test time. Used for history grouping when models/providers are renamed.', example: 'openrouter' })
  @Column()
  providerKey!: string;

  @ApiProperty({ description: 'Provider-specific model name at test time.', example: 'meta-llama/llama-3.1-70b-instruct' })
  @Column()
  modelName!: string;

  @ApiProperty({ description: 'Display label snapshot at test time.', example: 'Llama 3.1 70B Instruct' })
  @Column()
  modelLabel!: string;

  @ApiProperty({ description: 'Whether the provider/model responded at all (network, auth, etc.).', example: true })
  @Column({ default: false })
  available!: boolean;

  @ApiProperty({ description: 'Whether the test prompt returned a non-error response.', example: true })
  @Column({ default: false })
  success!: boolean;

  @ApiProperty({ description: 'Error message if available=false or success=false. Null on success.', example: null, nullable: true })
  @Column({ nullable: true, type: 'text' })
  errorMessage!: string | null;

  @ApiProperty({ description: 'End-to-end latency in milliseconds, or null if unavailable.', example: 1240.5, nullable: true })
  @Column({ nullable: true, type: 'float' })
  latencyMs!: number | null;

  @ApiProperty({ description: 'Time to first token in milliseconds (streaming only), or null.', example: 410.0, nullable: true })
  @Column({ nullable: true, type: 'float' })
  timeToFirstTokenMs!: number | null;

  @ApiProperty({ description: 'Throughput in tokens/second, or null if streaming was not measured.', example: 84.3, nullable: true })
  @Column({ nullable: true, type: 'float' })
  tokensPerSecond!: number | null;

  @ApiProperty({ description: 'Input tokens consumed by the test prompt, or null if not reported.', example: 32, nullable: true })
  @Column({ nullable: true })
  inputTokens!: number | null;

  @ApiProperty({ description: 'Output tokens generated by the model, or null if not reported.', example: 215, nullable: true })
  @Column({ nullable: true })
  outputTokens!: number | null;

  @ApiProperty({
    description: 'Heuristic quality score in [0, 1]. Until a judge model is wired in, computed from response length.',
    example: 0.7,
    nullable: true,
  })
  @Column({ nullable: true, type: 'float' })
  qualityScore!: number | null;

  @ApiProperty({
    description: 'Human-readable explanation of how the quality score was derived (e.g. "heuristic:length").',
    example: 'heuristic:length',
    nullable: true,
  })
  @Column({ nullable: true, type: 'text' })
  qualityReason!: string | null;

  @ApiProperty({ description: 'Timestamp when the test was executed.', example: '2026-05-12T10:02:11Z' })
  @Column()
  testedAt!: Date;
}
